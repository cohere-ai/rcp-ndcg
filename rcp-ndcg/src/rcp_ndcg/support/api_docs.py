"""The generated API reference: one Markdown page per public module, from the pinned surface snapshot.

The public surface is pinned as data (``tests/contract/snapshots/python_api.json``: the ``__all__`` of
:data:`PUBLIC_MODULES`, each name with its kind, signature and model fields). ``rcp-ndcg docs api --out
docs/reference/api`` renders that snapshot plus the modules' own docstrings into one page per module -- every
public name with its signature and one-line role -- so the long tail of the surface is documented mechanically
while the curated pages under ``docs/`` carry the narrative. The contract suite regenerates the pages and diffs
them against the committed copies, so the docs cannot drift from the surface.
"""

